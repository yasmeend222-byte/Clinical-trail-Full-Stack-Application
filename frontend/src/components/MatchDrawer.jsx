import { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { api, fmtDate } from "../api";
import { Badge, ErrorBox, ScoreBar, Spinner } from "./ui";

const REVIEW_ACTIONS = [
  ["approved", "Approve"],
  ["contacted", "Mark contacted"],
  ["enrolled", "Enrolled"],
  ["rejected", "Reject"],
];

export default function MatchDrawer({ matchId, onClose, onChange, context = "trial" }) {
  const [m, setM] = useState(null);
  const [error, setError] = useState(null);
  const [notes, setNotes] = useState("");
  const [busy, setBusy] = useState("");

  useEffect(() => {
    if (!matchId) return;
    setM(null);
    setError(null);
    api(`/api/matches/${matchId}`)
      .then((d) => {
        setM(d);
        setNotes(d.review_notes || "");
      })
      .catch(setError);
  }, [matchId]);

  useEffect(() => {
    const onKey = (e) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);

  if (!matchId) return null;

  const review = async (status) => {
    setBusy(status);
    try {
      const d = await api(`/api/matches/${matchId}/review`, { method: "PATCH", body: { review_status: status, review_notes: notes } });
      setM(d);
      onChange?.(d);
    } catch (e) {
      setError(e);
    } finally {
      setBusy("");
    }
  };

  const regenerate = async () => {
    setBusy("explain");
    try {
      const d = await api(`/api/matches/${matchId}/explain`, { method: "POST" });
      setM(d);
    } catch (e) {
      setError(e);
    } finally {
      setBusy("");
    }
  };

  const groups = m ? ["inclusion", "exclusion"].map((t) => [t, m.criteria_results.filter((r) => r.type === t)]) : [];

  return (
    <div className="drawer-backdrop" onClick={onClose}>
      <aside className="drawer" onClick={(e) => e.stopPropagation()} role="dialog" aria-label="Match details">
        <header className="drawer-head">
          <div>
            <div className="eyebrow">{context === "trial" ? "Candidate evaluation" : "Trial evaluation"}</div>
            {m ? (
              <h2>
                {context === "trial" ? (
                  <Link to={`/patients/${m.patient_id}`}>{m.patient.name}</Link>
                ) : (
                  <Link to={`/trials/${m.trial_id}`}>{m.trial_title}</Link>
                )}
              </h2>
            ) : <h2>Loading…</h2>}
            {m && (
              <div className="muted small">
                {m.patient.mrn} · {m.patient.age ?? "?"} y · {m.patient.gender} · {m.trial_code} · updated {fmtDate(m.updated_at)}
              </div>
            )}
          </div>
          <button className="icon-btn" onClick={onClose} aria-label="Close">✕</button>
        </header>
        <ErrorBox error={error} />
        {m && (
          <div className="drawer-body">
            <div className="summary-row">
              <Badge status={m.eligibility_status} />
              <div className="grow"><ScoreBar value={m.confidence_score} /></div>
              <span className="muted small">semantic {(m.semantic_score * 100).toFixed(0)}%</span>
            </div>
            <div className="counts">
              <span className="pill green">{m.matched_count} met</span>
              <span className="pill red">{m.unmet_count} not met</span>
              <span className="pill amber">{m.unknown_count} unknown</span>
            </div>

            {m.missing_tests.length > 0 && (
              <section className="callout amber">
                <strong>Missing diagnostic data</strong>
                <ul>{m.missing_tests.map((t) => <li key={t.test}><b>{t.test}</b> — needed for “{t.reason}”</li>)}</ul>
              </section>
            )}

            <section>
              <div className="section-head">
                <h3>AI explanation</h3>
                <span className="muted small">{m.explanation_source === "llm" ? "Generated by LLM" : "Rule-based template"}</span>
                <button className="btn ghost small" onClick={regenerate} disabled={!!busy}>
                  {busy === "explain" ? <Spinner label="Generating" /> : "Regenerate"}
                </button>
              </div>
              <div className="explanation">{m.explanation}</div>
            </section>

            {groups.map(([type, rows]) => rows.length > 0 && (
              <section key={type}>
                <h3 className="cap">{type} criteria</h3>
                <div className="crit-results">
                  {rows.map((r) => (
                    <div key={r.criterion_id} className={`crit-result ${r.status}`}>
                      <div className="crit-result-head">
                        <Badge status={r.status} />
                        <span className="crit-desc">{r.description}</span>
                      </div>
                      <ul className="evidence">
                        {r.checks.map((c, i) => (
                          <li key={i}>
                            <span className="check-label">{c.label}</span>
                            <span className="muted"> — {c.evidence}</span>
                          </li>
                        ))}
                      </ul>
                    </div>
                  ))}
                </div>
              </section>
            ))}

            <section className="review">
              <h3>Coordinator review <Badge status={m.review_status} /></h3>
              <textarea rows={2} placeholder="Review notes (optional)" value={notes} onChange={(e) => setNotes(e.target.value)} />
              <div className="btn-row">
                {REVIEW_ACTIONS.map(([s, label]) => (
                  <button key={s} className={`btn small ${s === "rejected" ? "danger-outline" : s === "approved" ? "primary" : "ghost"}`}
                    onClick={() => review(s)} disabled={!!busy}>
                    {busy === s ? <Spinner /> : label}
                  </button>
                ))}
              </div>
            </section>
          </div>
        )}
      </aside>
    </div>
  );
}
